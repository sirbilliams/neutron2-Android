/*  ExeData.cpp - fills the data section (neg::g_data / neg::g_ptrs, see gen/globals.h) from the
    player's own Neutron2.exe at start-up.

    The original program starts with its .data section already holding the exe's initial values:
    text, tables, defaults. Those bytes are part of the game, so they are not in this source tree.
    Instead they are copied here from the Neutron2.exe in the game folder, which must be the
    clean retail exe: a crc32 of the block (generated by tools/decomp/globals.py) tells us it is.

    Not in the original: Windows loaded the image for it.                                       */

#include "gen/globals.h"
#include "OMediaSDLRetarget.h"
#include <SDL.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <zlib.h>
#include <vector>
#include <string>

namespace {

const unsigned int IMAGE_BASE = 0x400000;

unsigned int rd32(const std::vector<unsigned char> &f, size_t o)
{
	return o + 4 <= f.size() ? (unsigned int)f[o] | (unsigned int)f[o + 1] << 8 | (unsigned int)f[o + 2] << 16 | (unsigned int)f[o + 3] << 24 : 0;
}
unsigned int rd16(const std::vector<unsigned char> &f, size_t o)
{
	return o + 2 <= f.size() ? (unsigned int)f[o] | (unsigned int)f[o + 1] << 8 : 0;
}

struct Section { unsigned int va, vsize, raw, rawsize; };

// Copy `n` bytes of the loaded image at virtual address `va` into `out` (bytes outside the
// file's raw data are zero, as the loader leaves them).
void ReadImage(const std::vector<unsigned char> &f, const std::vector<Section> &secs, unsigned int va,
			   unsigned char *out, unsigned int n)
{
	memset(out, 0, n);
	for (size_t i = 0; i < secs.size(); i++)
	{
		const Section &s = secs[i];
		unsigned int lo = IMAGE_BASE + s.va, hi = lo + (s.vsize > s.rawsize ? s.vsize : s.rawsize);
		for (unsigned int a = va > lo ? va : lo; a < va + n && a < hi; a++)
		{
			unsigned int r = a - lo;
			if (r < s.rawsize && s.raw + r < f.size()) out[a - va] = f[s.raw + r];
		}
	}
}

}	// namespace

// Returns false (with the reason in `why`) when there is no usable Neutron2.exe.
bool neg::LoadExeData(char *why, int why_size)
{
	std::string path = omf_SDLResolvePath("Neutron2.exe");
	FILE *fp = fopen(path.c_str(), "rb");
	if (!fp)
	{
		snprintf(why, why_size, "Neutron2.exe was not found in the game folder.\n"
				 "Copy it there from your installed game (Program_Executable_Files).");
		return false;
	}
	std::vector<unsigned char> f;
	unsigned char buf[65536];
	size_t n;
	while ((n = fread(buf, 1, sizeof buf, fp)) > 0) f.insert(f.end(), buf, buf + n);
	fclose(fp);

	unsigned int pe = rd32(f, 0x3c);
	if (f.size() < 0x40 || f[0] != 'M' || f[1] != 'Z' || rd32(f, pe) != 0x4550 || rd32(f, pe + 0x34) != IMAGE_BASE)
	{
		snprintf(why, why_size, "Neutron2.exe in the game folder is not a valid copy of the game.");
		return false;
	}
	unsigned int nsec = rd16(f, pe + 6), opt = rd16(f, pe + 0x14);
	std::vector<Section> secs;
	for (unsigned int i = 0; i < nsec; i++)
	{
		size_t h = pe + 0x18 + opt + i * 0x28;
		Section s = { rd32(f, h + 12), rd32(f, h + 8), rd32(f, h + 20), rd32(f, h + 16) };
		secs.push_back(s);
	}

	ReadImage(f, secs, DATA_BASE, g_data, g_exe_init_size);
	unsigned int crc = (unsigned int)crc32(0L, g_data, g_exe_init_size);
	if (crc != g_exe_init_crc)
	{
		memset(g_data, 0, g_exe_init_size);
		snprintf(why, why_size, "Neutron2.exe in the game folder is a different version (data crc %08x, "
				 "expected %08x).\nUse the original retail Neutron2.exe.", crc, g_exe_init_crc);
		return false;
	}

	// Pointer slots that start out pointing at a string: point them at a copy of that string.
	for (const unsigned int *s = g_string_slots; *s; s++)
	{
		unsigned int va = 0;
		memcpy(&va, &g_data[*s * 4], 4);
		char str[257];
		ReadImage(f, secs, va, (unsigned char *)str, 256);
		str[256] = 0;
		g_ptrs[*s] = strdup(str);
	}
	SDL_Log("ExeData: %u bytes of initial data from %s", g_exe_init_size, path.c_str());
	return true;
}
