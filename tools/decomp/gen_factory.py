#!/usr/bin/env python3
"""Write game/src/gen/factory.cpp from factory.json (tools/decomp/factory.py): neg::CreateObject,
the 4-char-ID -> class switch of 0x4912d0. Each class is built by `neg::New_<Class>()`; a weak
default (logging TODO and returning NULL) is generated for every class, and the class's own
source overrides it with a strong definition once the class is reconstructed:

    CGameObject *neg::New_C3DJimmy() { return new C3DJimmy(); }   // in C3DJimmy.cpp
"""
import json, sys
rows = json.load(open(sys.argv[1]))
out = ['// generated by tools/decomp/gen_factory.py from the object factory of Neutron2.exe (0x4912d0) - do not edit',
       '#include "../CGameObject.h"', '#include "../Todo.h"', '', 'namespace neg {', '']
classes = {}
for r in rows:
    cls = 'CMenuElement' if r['cls'] == 'CMENUELEMENT' else r['cls']
    classes.setdefault(cls, r)
for cls, r in sorted(classes.items()):
    out.append(f'CGameObject *New_{cls}(void);')
out.append('')
for cls, r in sorted(classes.items()):
    out.append(f'__attribute__((weak)) CGameObject *New_{cls}(void)\t{{ NEG_TODO({r["ctor"]}, "new {cls} ({r["size"]} bytes)"); return 0; }}')
out += ['', 'CGameObject *CreateObject(int id)\t\t\t\t// 0x4912d0', '{', '\tswitch (id)', '\t{']
for r in sorted(rows, key=lambda r: int(r['idval'], 16)):
    cls = 'CMenuElement' if r['cls'] == 'CMENUELEMENT' else r['cls']
    out.append(f"\t\tcase '{r['id']}': return New_{cls}();\t\t// {r['size']} bytes, ctor {r['ctor']}, CGameObject at +{r['subobject']}")
out += ['\t}', '\treturn 0;', '}', '', '}']
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(f'{len(rows)} IDs, {len(classes)} classes')
